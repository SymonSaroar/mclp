"""Builds the bare-metal console with the Vitis 2025.1 Python API, a JTAG load script and BOOT.BIN.

    vitis -s sw/baremetal/build.py [path/to/mclp.xsa]

Default XSA: build/mclp.xsa (README, Build from source). The Vitis workspace is recreated in
build/vitis. Outputs:
    build/vitis/mclp_app/build/mclp_app.elf
    build/vitis/jtag.tcl        xsdb build/vitis/jtag.tcl: program the PL, init the PS, run the console
    build/sd/BOOT.BIN           FSBL, bitstream and console for SD boot
"""
import glob
import os
import shutil
import subprocess
import sys

import vitis

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
XSA = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, "build", "mclp.xsa")
WS = os.path.join(ROOT, "build", "vitis")
SD = os.path.join(ROOT, "build", "sd")
CPU, DOMAIN = "ps7_cortexa9_0", "standalone_a9"


def find(pattern):
    hits = sorted(glob.glob(os.path.join(WS, pattern), recursive=True))
    if not hits:
        sys.exit(f"not found in {WS}: {pattern}")
    return hits[0].replace("\\", "/")


if not os.path.isfile(XSA):
    sys.exit(f"XSA not found: {XSA}. Export it with write_hw_platform (README, Build from source).")
shutil.rmtree(WS, ignore_errors=True)

client = vitis.create_client()
client.set_workspace(path=WS)

platform = client.create_platform_component(name="mclp_platform", hw_design=XSA, os="standalone",
                                            cpu=CPU, domain_name=DOMAIN)
platform.get_domain(name=DOMAIN).set_lib(lib_name="xilffs")    # FAT on the SD card: 0:/mclp.cal
platform.build()

app = client.create_app_component(name="mclp_app", platform=find("mclp_platform/export/**/*.xpfm"),
                                  domain=DOMAIN, template="empty_application")
for src in (os.path.join(HERE, "src"), os.path.join(HERE, "..", "common")):    # flat: Vitis builds src/*.c
    files = sorted(f for f in os.listdir(src) if f.endswith((".c", ".h")))
    app.import_files(from_loc=os.path.normpath(src), files=files, dest_dir_in_cmp="src")
app.set_app_config(key="USER_LINK_LIBRARIES", values=["xilffs", "m"])
app.build()
vitis.dispose()

elf, bit = find("mclp_app/build/*.elf"), find("mclp_platform/**/*.bit")
fsbl, ps7_init = find("mclp_platform/**/fsbl.elf"), find("mclp_platform/**/ps7_init.tcl")

with open(os.path.join(WS, "jtag.tcl"), "w") as f:
    f.write(f"""# Generated by sw/baremetal/build.py. Run: xsdb build/vitis/jtag.tcl
connect
targets -set -nocase -filter {{name =~ "APU*"}}
rst -system
after 1000
targets -set -nocase -filter {{name =~ "xc7z*"}}
fpga -file {{{bit}}}
targets -set -nocase -filter {{name =~ "APU*"}}
source {{{ps7_init}}}
ps7_init
ps7_post_config
targets -set -nocase -filter {{name =~ "*A9*#0"}}
dow {{{elf}}}
con
""")

os.makedirs(SD, exist_ok=True)
bif = os.path.join(SD, "boot.bif")
with open(bif, "w") as f:
    f.write(f"the_ROM_image:\n{{\n\t[bootloader] {fsbl}\n\t{bit}\n\t{elf}\n}}\n")
vitis_dir = os.environ.get("XILINX_VITIS", "")
bootgen = shutil.which("bootgen") or shutil.which(os.path.join(vitis_dir, "bin", "bootgen"))
cmd = [bootgen or "bootgen", "-arch", "zynq", "-image", bif, "-o", os.path.join(SD, "BOOT.BIN"), "-w", "on"]
if bootgen:
    subprocess.run(cmd, check=True)
    print(f"\nBOOT.BIN: {os.path.join(SD, 'BOOT.BIN')}")
else:
    print("\nbootgen not on PATH; run:\n  " + " ".join(cmd))
print(f"ELF:      {elf}\nJTAG:     xsdb {os.path.join(WS, 'jtag.tcl')}")
